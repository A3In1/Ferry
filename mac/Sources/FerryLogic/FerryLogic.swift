import CryptoKit
import Foundation

/// An http(s) URL with a host, or nil. Links from the phone are only opened if this passes.
public func webURL(_ text: String) -> URL? {
    let s = text.trimmingCharacters(in: .whitespacesAndNewlines)
    guard !s.contains(where: \.isWhitespace),
          let url = URL(string: s),
          let scheme = url.scheme?.lowercased(), scheme == "http" || scheme == "https",
          url.host?.isEmpty == false
    else { return nil }
    return url
}

/// Notification category id for a set of phone buttons (id, title, takes reply).
/// Deterministic across launches so notifications still in Notification Center keep their buttons.
public func categoryID(_ buttons: [(id: String, title: String, reply: Bool)]) -> String {
    // Length-prefixed fields so ("a|b","c") and ("a","b|c") can't collide.
    let key = buttons.map { "\($0.id.count):\($0.id)\($0.title.count):\($0.title)\($0.reply ? 1 : 0)" }.joined()
    let digest = SHA256.hash(data: Data(key.utf8))
    return "p|" + digest.prefix(8).map { String(format: "%02x", $0) }.joined()
}

